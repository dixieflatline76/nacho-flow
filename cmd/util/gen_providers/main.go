package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

type providerEntry struct {
	constName string
	value     string
}

func main() {
	root := "../.."
	if _, err := os.Stat("pkg/provider"); err == nil {
		root = "."
	}
	providerDir := filepath.Join(root, "pkg", "provider")
	outFile := filepath.Join(providerDir, "zz_generated_providers.go")

	entries, err := os.ReadDir(providerDir)
	if err != nil {
		fmt.Fprintf(os.Stderr, "failed to read %s: %v\n", providerDir, err)
		os.Exit(1)
	}

	typeRegex := regexp.MustCompile(`(Type[A-Za-z0-9_]+)\s+contract\.ProviderType\s*=\s*"([^"]+)"`)
	var discovered []providerEntry

	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") || strings.HasSuffix(e.Name(), "_test.go") || strings.HasPrefix(e.Name(), "zz_generated_") {
			continue
		}
		raw, err := os.ReadFile(filepath.Join(providerDir, e.Name()))
		if err != nil {
			continue
		}
		matches := typeRegex.FindAllStringSubmatch(string(raw), -1)
		for _, m := range matches {
			if len(m) >= 3 {
				discovered = append(discovered, providerEntry{
					constName: m[1],
					value:     m[2],
				})
			}
		}
	}

	sort.Slice(discovered, func(i, j int) bool {
		return discovered[i].constName < discovered[j].constName
	})

	var sb strings.Builder
	sb.WriteString("// Code generated by gen_providers; DO NOT EDIT.\n\n")
	sb.WriteString("package provider\n\n")
	sb.WriteString("import \"github.com/dixieflatline76/nacho-flow/pkg/contract\"\n\n")
	sb.WriteString("// ValidProviderTypes lists all discovered wire-protocol provider types.\n")
	sb.WriteString("var ValidProviderTypes = []contract.ProviderType{\n")
	for _, d := range discovered {
		sb.WriteString(fmt.Sprintf("\t%s,\n", d.constName))
	}
	sb.WriteString("}\n")

	if err := os.WriteFile(outFile, []byte(sb.String()), 0600); err != nil {
		fmt.Fprintf(os.Stderr, "failed to write %s: %v\n", outFile, err)
		os.Exit(1)
	}
}
